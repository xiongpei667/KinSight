export function createI18n(lang) {
  const dict = translations[lang] || translations.zh;
  return {
    t: (key, params = {}) => {
      let text = dict[key];
      if (text === undefined) return key;
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{${k}}`, v);
      }
      return text;
    },
    lang,
  };
}
